"""Generate build-start UTC identity; never reuse a timestamp from a prior build."""
from datetime import datetime, timezone
import hashlib
import json
import re


def generate(sketch, now=None):
    instant = now or datetime.now(timezone.utc)
    if instant.tzinfo is None or instant.utcoffset() is None:
        raise ValueError("Build time must be timezone-aware")
    stamp = instant.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    version = re.search(r'kFirmwareVersion\[\]\s*=\s*"([^"]+)"',
                        (sketch / "firmware_version.h").read_text()).group(1)
    (sketch / "firmware_build.h").write_text(
        '#pragma once\n// Generated by scripts/build.py; do not edit or commit.\n'
        f'constexpr char kFirmwareBuildUtc[] = "{stamp}";\n', encoding="utf-8")
    return {"firmware_version": version, "build_time_utc": stamp}


def verify(binary, metadata):
    payload = binary.read_bytes()
    for key in ("firmware_version", "build_time_utc"):
        if metadata[key].encode() + b"\0" not in payload:
            raise RuntimeError(f"Application does not contain current {key}")
    return dict(metadata, application_sha256=hashlib.sha256(payload).hexdigest())


def write_manifest(build, metadata):
    (build / "build_manifest.json").write_text(json.dumps(metadata, indent=2) + "\n")


def check_policy(root):
    required = ("Rules_Versioning.md", "Rules_Change_Notifications.md")
    agents = (root / "AGENTS.md").read_text(encoding="utf-8")
    for name in required:
        if name not in agents:
            raise RuntimeError(f"Mandatory AI entrypoint missing: {name}")
    vault = next((root.parent / name for name in ("2026 Vault Firmware Rules", "2026-vault-firmware-rules")
                  if (root.parent / name).exists()), None)
    if vault:
        for name in required:
            if not (vault / "01_Rules" / name).read_text(encoding="utf-8").strip():
                raise RuntimeError(f"Empty mandatory rule: {name}")
        print("Read Obsidian: " + ", ".join(required))
